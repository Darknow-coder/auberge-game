export const DICTS = { fr: FR, en: EN };
export const LANGS = ['fr', 'en'];
let lang = 'fr';

export function detectLang() {
  const nav = (typeof navigator !== 'undefined' && (navigator.languages?.[0] || navigator.language)) || 'fr';
  return nav.toLowerCase().startsWith('fr') ? 'fr' : 'en';
}

export function setLang(l) {
  lang = LANGS.includes(l) ? l : 'fr';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

export const getLang = () => lang;

export function t(key, vars) {
  let s = DICTS[lang][key] ?? DICTS.fr[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll(`{${k}}`, vars[k]);
  // Typographie française : espace insécable avant ! ? : ;
  if (lang === 'fr') s = s.replace(/ ([!?:;])/g, '\u00a0$1');
  return s;
}

/** Nombre formaté selon la langue (espaces fines en français). */
export function fmt(n) {
  return Math.round(n).toLocaleString(lang === 'fr' ? 'fr-FR' : 'en-US');
}
